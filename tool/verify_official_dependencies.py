#!/usr/bin/env python3
"""Verify the complete hosted graph and pinned official SDK source/runtime.

This reads dependency trees. It never repairs or modifies a package or SDK.
Official archives and the source-bound report are retained under ignored build/.
"""
from __future__ import annotations
import argparse
import hashlib
import datetime as dt
import json
import os
from pathlib import Path, PurePosixPath
import re
import stat
import subprocess
import tarfile
import time
import urllib.parse
import urllib.request
import uuid
from verify_upstream_packages import attest

MAX_ARCHIVE = 128 * 1024 * 1024
MAX_MEMBER = 128 * 1024 * 1024
MAX_EXPANDED = 2 * 1024 * 1024 * 1024
MAX_FILES = 16384
RUNTIME_DIRS = frozenset(('lib', 'bin', 'src', 'include', 'native', 'android',
    'ios', 'linux', 'macos', 'windows', 'web', 'assets', 'fonts', 'hook'))
ROOT_CONFIG = frozenset(('pubspec.yaml', 'analysis_options.yaml', 'CMakeLists.txt',
    'Cargo.toml', 'build.rs', 'Makefile'))

class IntegrityError(RuntimeError):
    pass

def owned_build_environment(root: Path) -> dict:
    """Resolve only the project's official cache and short private temp owner."""
    temporary = root / 'build/t'
    temporary.mkdir(mode=0o700, parents=True, exist_ok=True)
    info = temporary.lstat()
    if not stat.S_ISDIR(info.st_mode) or (hasattr(os, 'getuid') and info.st_uid != os.getuid()):
        raise IntegrityError('Build temporary directory is not owned by this verification user')
    temporary.chmod(0o700)
    return {**os.environ, 'PUB_CACHE': str(root / 'build/official-dependencies/pub-cache'),
            'TMPDIR': str(temporary)}

def publisher_attestation(root: Path, configuration: Path, locked: dict) -> dict:
    """One receipt also certifies the reviewed pins and actual SDK inputs."""
    try:
        return attest(configuration, root / 'tool/upstream_packages.json', locked)
    except (ValueError, OSError, KeyError, TypeError, subprocess.SubprocessError) as failure:
        raise IntegrityError('Official SDK/publisher attestation failed: ' + str(failure)) from failure

def json_file(path: Path, limit: int = 1048576) -> dict:
    if path.is_symlink() or not path.is_file() or path.stat().st_size > limit:
        raise IntegrityError('Missing, linked or oversized verification input: ' + path.name)
    return json.loads(path.read_text())

def uri_path(uri: str, relative_to: Path) -> Path:
    parsed = urllib.parse.urlparse(uri)
    if parsed.scheme not in ('', 'file') or parsed.netloc not in ('', 'localhost'):
        raise IntegrityError('Resolved package path is not a local file URI')
    raw = urllib.parse.unquote(parsed.path)
    if os.name == 'nt' and re.match(r'^/[A-Za-z]:', raw):
        raw = raw[1:]
    path = Path(raw)
    return path if parsed.scheme == 'file' else relative_to / path

def sha(path: Path) -> str:
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()

def required(path: PurePosixPath) -> bool:
    if len(path.parts) > 1:
        return path.parts[0] in RUNTIME_DIRS
    return path.name in ROOT_CONFIG or bool(re.fullmatch(
        r'(LICENSE|COPYING|NOTICE|AUTHORS)(\..*)?', path.name, re.I))

def parse_lock(path: Path) -> dict[str, dict]:
    if path.stat().st_size > 1048576:
        raise IntegrityError('Oversized pub lockfile')
    text = path.read_text()
    if len(text) > 1048576 or not text.startswith('# Generated by pub\n'):
        raise IntegrityError('Malformed or oversized pub lockfile')
    packages = {}
    for match in re.finditer(r'^  (_?[a-z][a-z0-9_]*):\n((?:^    .*\n|^\n)*)', text, re.M):
        name, block = match.groups()
        def scalar(key, indent=4):
            value = re.findall(r'^' + ' ' * indent + re.escape(key) + r':\s*(.*?)\s*$', block, re.M)
            if len(value) != 1:
                raise IntegrityError('Missing or duplicate lock field: ' + name + '.' + key)
            return value[0].strip('"')
        source, version = scalar('source'), scalar('version')
        if name in packages or not re.fullmatch(r'[0-9][A-Za-z0-9.+-]{0,63}', version):
            raise IntegrityError('Duplicate package or invalid locked version')
        entry = {'name': name, 'version': version, 'source': source}
        if source == 'hosted':
            if scalar('name', 6) != name or scalar('url', 6) != 'https://pub.dev':
                raise IntegrityError('Dependency must use the official pub registry: ' + name)
            digest = scalar('sha256', 6)
            if not re.fullmatch('[a-f0-9]{64}', digest):
                raise IntegrityError('Dependency archive has no exact SHA256: ' + name)
            entry['sha256'] = digest
        elif source != 'sdk':
            raise IntegrityError('Unverified non-hosted dependency source: ' + name)
        packages[name] = entry
    if not packages or len(packages) > 512:
        raise IntegrityError('Missing or oversized package graph')
    return packages

def official_metadata(entry: dict, cache: Path, deadline: float) -> dict:
    url = 'https://pub.dev/api/packages/' + entry['name'] + '/versions/' + urllib.parse.quote(entry['version'], safe='')
    with urllib.request.urlopen(url, timeout=min(30, max(1, deadline - time.monotonic()))) as response:
        raw = response.read(524289)
    if len(raw) > 524288:
        raise IntegrityError('Official metadata exceeds 512 KiB bound')
    metadata = json.loads(raw)
    expected_url = 'https://pub.dev/api/archives/' + entry['name'] + '-' + urllib.parse.quote(entry['version'], safe='') + '.tar.gz'
    if metadata.get('version') != entry['version'] or metadata.get('pubspec', {}).get('name') != entry['name'] or metadata.get('archive_sha256') != entry['sha256'] or metadata.get('archive_url') != expected_url:
        raise IntegrityError('Lockfile differs from official package version/archive identity: ' + entry['name'])
    path = cache / (entry['sha256'] + '.metadata.json')
    if path.is_symlink():
        raise IntegrityError('Retained official metadata path is linked')
    path.write_bytes(raw)
    return {'officialMetadataUrl': url, 'officialMetadataSha256': hashlib.sha256(raw).hexdigest(),
        'officialMetadataFetchedUtc': dt.datetime.now(dt.timezone.utc).isoformat()}


def archive_for(entry: dict, cache: Path, deadline: float) -> Path:
    target = cache / (entry['sha256'] + '.tar.gz')
    if target.is_file():
        if target.is_symlink() or target.stat().st_size > MAX_ARCHIVE or sha(target) != entry['sha256']:
            raise IntegrityError('Cached official archive changed: ' + entry['name'])
        return target
    partial = target.with_suffix('.partial')
    if partial.exists():
        raise IntegrityError('Incomplete archive requires explicit inspection: ' + str(partial))
    url = 'https://pub.dev/api/archives/' + entry['name'] + '-' + urllib.parse.quote(entry['version'], safe='') + '.tar.gz'
    digest, size = hashlib.sha256(), 0
    with urllib.request.urlopen(url, timeout=min(90, max(1, deadline - time.monotonic()))) as response, partial.open('xb') as sink:
        while chunk := response.read(65536):
            if time.monotonic() > deadline:
                raise IntegrityError('Official dependency verification timed out')
            size += len(chunk)
            if size > MAX_ARCHIVE:
                raise IntegrityError('Official archive exceeds 128 MiB bound: ' + entry['name'])
            digest.update(chunk)
            sink.write(chunk)
    if digest.hexdigest() != entry['sha256']:
        raise IntegrityError('Official dependency archive SHA256 mismatch: ' + entry['name'])
    partial.replace(target)
    return target

def verify_archive(archive: Path, package: Path, deadline: float) -> dict:
    expected, expanded, members = {}, 0, 0
    package = package.resolve(strict=True)
    with tarfile.open(archive, 'r|gz') as stream:
        for member in stream:
            if time.monotonic() > deadline:
                raise IntegrityError('Official dependency verification timed out')
            path = PurePosixPath(member.name)
            if path.is_absolute() or '..' in path.parts or not path.parts or '\\' in member.name or '\0' in member.name or re.match(r'^[A-Za-z]:', member.name):
                raise IntegrityError('Unsafe official archive path')
            members += 1
            expanded += member.size
            if members > MAX_FILES or member.size < 0 or member.size > MAX_MEMBER or expanded > MAX_EXPANDED:
                raise IntegrityError('Official package source exceeds verification bounds')
            if member.isdir():
                continue
            name = str(path)
            if name in expected or not member.isfile():
                raise IntegrityError('Duplicate or nonregular dependency source: ' + name)
            published = stream.extractfile(member)
            if published is None:
                raise IntegrityError('Unreadable official source member')
            digest, consumed = hashlib.sha256(), 0
            while chunk := published.read(65536):
                consumed += len(chunk)
                if consumed > member.size or time.monotonic() > deadline:
                    raise IntegrityError('Official source read exceeded bounds')
                digest.update(chunk)
            if consumed != member.size:
                raise IntegrityError('Truncated official source member')
            expected[name] = digest.hexdigest()
            actual = package / name
            if actual.is_symlink() or not actual.is_file() or actual.stat().st_size != member.size or not actual.resolve().is_relative_to(package) or sha(actual) != expected[name]:
                raise IntegrityError('Resolved dependency differs from official source: ' + name)
    actual_paths = set()
    pub_metadata = {'.dart_tool/package_config.json', '.dart_tool/package_graph.json', '.packages', 'pubspec.lock'}
    for directory, dirs, files in os.walk(package, followlinks=False):
        parent = Path(directory)
        for name in dirs:
            if (parent / name).is_symlink():
                raise IntegrityError('Resolved package contains an unverified directory link')
        for name in files:
            path = parent / name
            key = path.relative_to(package).as_posix()
            if path.is_symlink():
                raise IntegrityError('Resolved package contains an unverified file link')
            if key not in pub_metadata or key in expected:
                actual_paths.add(key)
        if len(actual_paths) > MAX_FILES:
            raise IntegrityError('Resolved dependency exceeds source file bound')
    if actual_paths != set(expected):
        missing = sorted(set(expected) - actual_paths)[:8]
        injected = sorted(actual_paths - set(expected))[:8]
        raise IntegrityError('Resolved dependency has missing or injected package files: ' +
            package.name + '; missing=' + repr(missing) + '; injected=' + repr(injected))
    if not expected:
        raise IntegrityError('Official dependency contains no verified runtime/configuration source')
    return {'publishedFilesVerified': len(expected),
        'runtimeConfigurationLicenseFiles': sum(required(PurePosixPath(path)) for path in expected),
        'runtimeSourceManifestSha256': hashlib.sha256(json.dumps(expected, sort_keys=True).encode()).hexdigest(),
        'archiveMembers': members, 'archiveExpandedBytes': expanded}

def verify(root: Path, cache: Path, deadline: float) -> dict:
    lock, configuration = root / 'pubspec.lock', root / '.dart_tool/package_config.json'
    locked = parse_lock(lock)
    data = json_file(configuration)
    owned_cache = root / 'build/official-dependencies/pub-cache'
    configured_cache = urllib.parse.urlparse(data.get('pubCache', ''))
    if configured_cache.scheme != 'file' or uri_path(data['pubCache'], configuration.parent).resolve() != owned_cache.resolve():
        raise IntegrityError('Resolved dependencies must use the project-owned official Pub cache')
    toolchain = json_file(root / 'config/toolchain.json')
    if data.get('flutterVersion') != toolchain.get('flutter') or data.get('generatorVersion') != toolchain.get('dart'):
        raise IntegrityError('Resolved graph was not generated by the exact approved Flutter/Dart toolchain')
    packages = data.get('packages', [])
    if not isinstance(packages, list) or len(packages) > 513:
        raise IntegrityError('Malformed resolved package graph')
    upstream = publisher_attestation(root, configuration, locked)
    seen, records = set(), []
    sdk = urllib.parse.urlparse(data.get('flutterRoot', ''))
    sdk_root = uri_path(data['flutterRoot'], configuration.parent).resolve() if sdk.scheme == 'file' else None
    for package in packages:
        name = package['name']
        if package.get('packageUri') != 'lib/':
            raise IntegrityError('Resolved package does not use its official library root')
        if name in seen:
            raise IntegrityError('Duplicate resolved package')
        seen.add(name)
        path = uri_path(package['rootUri'], configuration.parent)
        path = path.resolve(strict=True)
        if name == 'busydata':
            if path != root:
                raise IntegrityError('Application package resolves outside its source owner')
            continue
        entry = locked.get(name)
        if entry is None:
            raise IntegrityError('Resolved package is absent from lockfile: ' + name)
        if entry['source'] == 'sdk':
            if sdk_root is None or not path.is_relative_to(sdk_root):
                raise IntegrityError('SDK package resolves outside approved Flutter SDK')
            records.append({**entry, 'classification': 'SDK input; official source/runtime verified by the pinned SDK attestation'})
            continue
        if path != (owned_cache / 'hosted/pub.dev' / (name + '-' + entry['version'])).resolve():
            raise IntegrityError('Hosted dependency resolves outside its project-owned official package location')
        specification_path = path / 'pubspec.yaml'
        if specification_path.stat().st_size > 1048576:
            raise IntegrityError('Resolved package specification exceeds bound')
        specification = specification_path.read_text()
        for key, expected in (('name', name), ('version', entry['version'])):
            matches = re.findall(r'^' + key + r':\s*([^\s#]+)', specification, re.M)
            if len(matches) != 1 or matches[0].strip('\"\'') != expected:
                raise IntegrityError('Resolved package name/version differs from lockfile')
        provenance = official_metadata(entry, cache, deadline)
        archive = archive_for(entry, cache, deadline)
        records.append({**entry, **provenance, **verify_archive(archive, path, deadline)})
        print('Verified official package:', name, entry['version'], flush=True)
    if seen != set(locked) | {'busydata'}:
        raise IntegrityError('Resolved and locked package owners differ')
    return {'status': 'passed', 'scope': 'Every locked hosted package member, reviewed publisher pins and official SDK source/runtime; injected package sources rejected',
        'verifierSha256': sha(Path(__file__)),
        'pubspecLockSha256': sha(lock), 'packageConfigurationSha256': sha(configuration),
        'ownedPubCache': str(owned_cache), 'packages': records, 'publisherAttestation': upstream}

def revalidate_receipt(root: Path) -> dict:
    """Bind the packaged inventory to the earlier official-source gate and bytes."""
    output = root / 'build/official-dependencies'
    report_path = output / 'verification.json'
    report = json_file(report_path)
    configuration = root / '.dart_tool/package_config.json'
    if report.get('status') != 'passed' or report.get('verifierSha256') != sha(Path(__file__)) or report.get('pubspecLockSha256') != sha(root / 'pubspec.lock') or report.get('packageConfigurationSha256') != sha(configuration):
        raise IntegrityError('Official dependency receipt is missing, failed, or stale')
    packages = {entry['name']: entry for entry in json_file(configuration)['packages']}
    locked = parse_lock(root / 'pubspec.lock')
    records = {entry['name']: entry for entry in report['packages']}
    if set(records) != set(locked) or set(packages) != set(locked) | {'busydata'}:
        raise IntegrityError('Official dependency receipt has incomplete package ownership')
    previous = report.get('publisherAttestation', {})
    if previous.get('catalogSha256') != sha(root / 'tool/upstream_packages.json') or previous.get('verifierSha256') != sha(Path(__file__).with_name('verify_upstream_packages.py')):
        raise IntegrityError('Official publisher/SDK attestation receipt is missing or stale')
    upstream = publisher_attestation(root, configuration, locked)
    if (upstream['reviewedPackages'] != previous.get('reviewedPackages') or
            any(upstream['sdk'][key] != previous.get('sdk', {}).get(key) for key in ('root', 'host', 'identity'))):
        raise IntegrityError('Official publisher/SDK owner changed after verification')
    original_inputs = previous.get('sdk', {}).get('artifactInputs')
    if not isinstance(original_inputs, dict) or not original_inputs or any(upstream['sdk']['artifactInputs'].get(path) != value for path, value in original_inputs.items()):
        raise IntegrityError('Previously verified SDK runtime input changed or disappeared')
    deadline = time.monotonic() + 1200
    verified_files = 0
    for name, entry in locked.items():
        record = records[name]
        if record.get('version') != entry['version'] or record.get('source') != entry['source']:
            raise IntegrityError('Official dependency receipt changed package identity')
        if entry['source'] == 'sdk':
            continue
        if record.get('sha256') != entry['sha256']:
            raise IntegrityError('Official dependency receipt changed archive identity')
        archive = output / 'archives' / (entry['sha256'] + '.tar.gz')
        metadata_path = output / 'archives' / (entry['sha256'] + '.metadata.json')
        if not archive.is_file() or archive.is_symlink() or archive.stat().st_size > MAX_ARCHIVE or sha(archive) != entry['sha256']:
            raise IntegrityError('Retained official artifact/provenance changed before packaging')
        metadata = json_file(metadata_path, 524288)
        if sha(metadata_path) != record.get('officialMetadataSha256'):
            raise IntegrityError('Retained official metadata changed before packaging')
        if metadata.get('archive_sha256') != entry['sha256'] or metadata.get('version') != entry['version'] or metadata.get('pubspec', {}).get('name') != name:
            raise IntegrityError('Retained official metadata no longer proves package identity')
        package = uri_path(packages[name]['rootUri'], configuration.parent)
        proof = verify_archive(archive, package, deadline)
        if proof['runtimeSourceManifestSha256'] != record.get('runtimeSourceManifestSha256'):
            raise IntegrityError('Resolved dependency bytes changed after the official-source gate')
        verified_files += proof['publishedFilesVerified']
    return {'status': 'passed', 'report': str(report_path.relative_to(root)),
        'reportSha256': sha(report_path), 'pubspecLockSha256': sha(root / 'pubspec.lock'),
        'verifierSha256': report['verifierSha256'],
        'packageConfigurationSha256': sha(configuration), 'revalidatedPublishedFiles': verified_files,
        'publisherAttestation': upstream, 'scope': report['scope']}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    root = args.root.resolve(strict=True)
    output = root / 'build/official-dependencies'
    output.mkdir(parents=True, exist_ok=True)
    cache = output / 'archives'
    cache.mkdir(exist_ok=True)
    started = dt.datetime.now(dt.timezone.utc).isoformat()
    invocation = str(uuid.uuid4())
    try:
        report = verify(root, cache, time.monotonic() + 1200)
    except Exception as error:
        report = {'status': 'failed', 'reason': type(error).__name__, 'detail': str(error)}
    report.update({'invocationId': invocation, 'startedUtc': started,
        'finishedUtc': dt.datetime.now(dt.timezone.utc).isoformat(),
        'verifierSha256': sha(Path(__file__))})
    retained = output / 'runs'
    retained.mkdir(exist_ok=True)
    encoded = json.dumps(report, indent=2) + '\n'
    (retained / (invocation + '.json')).write_text(encoded)
    latest = output / 'verification.json.partial'
    latest.write_text(encoded)
    latest.replace(output / 'verification.json')
    print('Official dependency and SDK source verification:', report['status'])
    return 0 if report['status'] == 'passed' else 1

if __name__ == '__main__':
    raise SystemExit(main())
